"""Export the base-case results used in the report and slides.

Usage:  python scripts/export_results.py
Writes results/*.csv and results/summary.md (10,000 trials, seed 14817, base assumptions,
recommended portfolio), so every number quoted in the deliverables can be regenerated.
"""
from pathlib import Path
import sys

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from insider_risk.categorize import campaigns, categorize, observation_years  # noqa: E402
from insider_risk.controls import (  # noqa: E402
    best_portfolio, cheapest_within_appetite, control_value_table, evaluate_all_portfolios, scenario_reduction,
)
from insider_risk.data import (  # noqa: E402
    BUSINESS_UNITS, RESPONSE_TEAMS, load_benchmarks, load_control_effects, load_controls, load_reports,
    load_scenarios,
)
from insider_risk.quantify import (  # noqa: E402
    Assumptions, apply_controls, build_inputs, calibration_check, exceedance_probability,
    expected_annual_loss, frequency_posterior, simulate, summarize,
)
from insider_risk.sensitivity import recommendation_stability, tornado  # noqa: E402

N, SEED, THRESHOLD = 10_000, 14817, 100e6
OUT = ROOT / "results"


def m(x: float) -> str:
    return f"${x / 1e6:,.1f}M"


def main() -> None:
    OUT.mkdir(exist_ok=True)
    scenarios, controls, effects = load_scenarios(), load_controls(), load_control_effects()
    cat = categorize(load_reports(), scenarios)
    a = Assumptions()
    inputs = build_inputs(cat, scenarios, a)
    portfolios = evaluate_all_portfolios(inputs, controls, effects, threshold=THRESHOLD)
    best = best_portfolio(portfolios)
    residual_inputs = apply_controls(inputs, effects, best.controls)
    sim_in, sim_res = simulate(inputs, N, SEED), simulate(residual_inputs, N, SEED)
    s_in, s_res = summarize(sim_in.total), summarize(sim_res.total)

    fp = frequency_posterior(cat, scenarios, a)
    sr = scenario_reduction(inputs, effects, best.controls)
    cv = control_value_table(inputs, controls, effects, list(best.controls))
    depts = []
    for lens, names in (("unit", BUSINESS_UNITS), ("team", RESPONSE_TEAMS)):
        for name in names:
            i = build_inputs(cat, scenarios, a, lens, name)
            depts.append({"lens": lens, "department": name, "inherent_ale": expected_annual_loss(i),
                          "residual_ale": expected_annual_loss(apply_controls(i, effects, best.controls))})
    depts = pd.DataFrame(depts)
    tor = tornado(cat, scenarios, controls, effects, a, list(best.controls), metric="baseline")
    stab = recommendation_stability(cat, scenarios, controls, effects, a)
    calib = calibration_check(inputs, load_benchmarks())

    fp.to_csv(OUT / "frequency_posterior.csv", index=False)
    sr.to_csv(OUT / "scenario_loss.csv", index=False)
    cv.to_csv(OUT / "control_value.csv", index=False)
    depts.to_csv(OUT / "department_exposure.csv", index=False)
    tor.to_csv(OUT / "tornado.csv", index=False)
    stab.to_csv(OUT / "recommendation_stability.csv", index=False)
    portfolios.drop(columns="controls").to_csv(OUT / "all_portfolios.csv", index=False)
    calib.to_csv(OUT / "calibration_check.csv", index=False)

    lines = [
        "# Base-case results (auto-generated by scripts/export_results.py)",
        f"{N:,} Monte Carlo trials · seed {SEED} · {len(cat)} intake reports over "
        f"{observation_years(cat) * 365.25:.0f} days · {len(campaigns(cat))} linked loss campaigns",
        "",
        "## Company-wide annual loss",
        "| Statistic | Inherent | With recommended portfolio |",
        "|---|---|---|",
    ]
    for label, key in (("Mean (expected loss)", "mean"), ("Median", "median"), ("P10", "p10"), ("P90", "p90"),
                       ("P95 (1-in-20)", "p95"), ("P99 (1-in-100)", "p99"), ("TVaR 95", "tvar95")):
        lines.append(f"| {label} | {m(s_in[key])} | {m(s_res[key])} |")
    lines += [
        f"| P(loss ≥ $100M) | {exceedance_probability(sim_in.total, THRESHOLD):.1%} | "
        f"{exceedance_probability(sim_res.total, THRESHOLD):.1%} |",
        f"| P(loss ≥ $180M) | {exceedance_probability(sim_in.total, 180e6):.1%} | "
        f"{exceedance_probability(sim_res.total, 180e6):.1%} |",
        f"| P(loss ≥ $345.2M, FY2025 actual) | {exceedance_probability(sim_in.total, 345.2e6):.1%} | "
        f"{exceedance_probability(sim_res.total, 345.2e6):.1%} |",
        "",
        "## Recommended portfolio (maximize net benefit)",
        f"- Controls: **{best.portfolio}**",
        f"- Annual cost {m(best.annual_cost)}; loss avoided {m(best.loss_avoided)}; net benefit "
        f"{m(best.net_benefit)}; ROSI {best.rosi:.0%}",
    ]
    for p in (0.05, 0.02, 0.01):
        pick = cheapest_within_appetite(portfolios, p)
        lines.append(f"- Cheapest portfolio with P(≥$100M) ≤ {p:.0%}: "
                     + ("none feasible" if pick is None else f"{pick.portfolio} ({m(pick.annual_cost)}/yr)"))
    lines += ["", "## Expected loss by scenario", "| Scenario | Inherent | Residual | Reduction |", "|---|---|---|---|"]
    for _, r in sr.iterrows():
        lines.append(f"| {r.scenario} | {m(r.inherent)} | {m(r.residual)} | {r.reduction_pct:.0%} |")
    lines += ["", "## Department exposure", "| View | Department | Inherent | Residual |", "|---|---|---|---|"]
    for _, r in depts.iterrows():
        lines.append(f"| {'Business unit' if r.lens == 'unit' else 'Response team'} | {r.department} | "
                     f"{m(r.inherent_ale)} | {m(r.residual_ale)} |")
    lines += ["", "## Frequency posterior", "| Scenario | Weighted events | Prior/yr | Observed/yr | Posterior/yr |",
              "|---|---|---|---|---|"]
    for _, r in fp.iterrows():
        lines.append(f"| {r.scenario_id} | {r.effective_events:.1f} | {r.prior_rate:.2f} | {r.observed_rate:.2f} | "
                     f"{r.posterior_rate:.2f} |")
    lines += ["", "## Largest sensitivities (inherent expected loss)"]
    for _, r in tor.sort_values("swing", ascending=False).head(4).iterrows():
        lines.append(f"- {r.parameter}: {m(min(r.at_low, r.at_high))} to {m(max(r.at_low, r.at_high))}")
    (OUT / "summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
